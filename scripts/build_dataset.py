"""Builds the training dataset from NHANES and writes data/nhanes_intake.csv.

DATA SOURCE AND LICENCE
-----------------------
NHANES (National Health and Nutrition Examination Survey), 2017-2018 cycle,
published by the US CDC / National Center for Health Statistics. NHANES data are
in the public domain and free to use without permission.

    https://wwwn.cdc.gov/nchs/nhanes/continuousnhanes/default.aspx?BeginYear=2017

Three files are joined on SEQN, the respondent identifier:

    DEMO_J.xpt    demographics   - age (RIDAGEYR), sex (RIAGENDR)
    BMX_J.xpt     body measures  - height (BMXHT), weight (BMXWT), BMI (BMXBMI)
    DR1TOT_J.xpt  day-1 dietary recall - energy (DR1TKCAL) and macros

WHY THIS REPLACED THE ORIGINAL DATASET
--------------------------------------
The project originally trained on data/macro_targets.xlsx, 99 rows in which
every macro target was a fixed multiple of the calorie column (grams per
calorie: std 0.0001, correlation with calories 0.9999). Those labels were
generated by a formula, so the model could only ever rediscover the formula -
and being tree-based it could not extrapolate, returning identical predictions
above its 2,953 kcal ceiling.

NHANES records what real people actually ate. The same protein-per-calorie
ratio has a standard deviation roughly 89 times larger, which is the variation
a model needs in order to have anything to learn.

PREPROCESSING
-------------
    - adults only, ages 18-80
    - complete cases on all features and targets
    - plausible intake only: 800-5000 kcal, and positive protein/carb/fat
      (NHANES includes non-response and partial recalls that would otherwise
      enter as zeros)
    - sex recoded to a 0/1 SEX_MALE column

Run:  python scripts/build_dataset.py
"""

import io
import ssl
import urllib.request
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parent.parent
DATA_DIR = ROOT / "data"
OUTPUT = DATA_DIR / "nhanes_intake.csv"

BASE_URL = "https://wwwn.cdc.gov/Nchs/Data/Nhanes/Public/2017/DataFiles/"

FILES = {
    "DEMO_J.xpt": ["SEQN", "RIAGENDR", "RIDAGEYR"],
    "BMX_J.xpt": ["SEQN", "BMXHT", "BMXWT", "BMXBMI"],
    "DR1TOT_J.xpt": ["SEQN", "DR1TKCAL", "DR1TPROT", "DR1TCARB", "DR1TTFAT", "DR1TSUGR"],
}

COLUMN_NAMES = {
    "RIDAGEYR": "age_years",
    "BMXHT": "height_cm",
    "BMXWT": "weight_kg",
    "BMXBMI": "bmi",
    "DR1TKCAL": "energy_kcal",
    "DR1TPROT": "protein_g",
    "DR1TCARB": "carbs_g",
    "DR1TTFAT": "fat_g",
    "DR1TSUGR": "sugar_g",
}


def _download(filename: str) -> pd.DataFrame:
    request = urllib.request.Request(
        BASE_URL + filename, headers={"User-Agent": "Mozilla/5.0"}
    )
    with urllib.request.urlopen(
        request, timeout=180, context=ssl.create_default_context()
    ) as response:
        payload = response.read()

    print(f"  {filename}: {len(payload) / 1048576:.1f} MB")
    return pd.read_sas(io.BytesIO(payload), format="xport")


def build() -> pd.DataFrame:
    print(f"Downloading NHANES 2017-2018 from {BASE_URL}")
    frames = {
        name: _download(name)[columns] for name, columns in FILES.items()
    }

    merged = (
        frames["DEMO_J.xpt"]
        .merge(frames["BMX_J.xpt"], on="SEQN")
        .merge(frames["DR1TOT_J.xpt"], on="SEQN")
    )
    print(f"\nJoined on SEQN: {len(merged)} respondents")

    merged = merged[merged["RIDAGEYR"].between(18, 80)]
    merged = merged.dropna()
    merged = merged[
        merged["DR1TKCAL"].between(800, 5000)
        & (merged["DR1TPROT"] > 0)
        & (merged["DR1TCARB"] > 0)
        & (merged["DR1TTFAT"] > 0)
    ]

    # RIAGENDR is 1 = male, 2 = female.
    merged["SEX_MALE"] = (merged["RIAGENDR"] == 1).astype(int)
    merged = merged.drop(columns=["RIAGENDR", "SEQN"]).rename(columns=COLUMN_NAMES)

    print(f"After filtering to usable adult records: {len(merged)}")
    print(
        f"Energy range: {merged['energy_kcal'].min():.0f}"
        f" - {merged['energy_kcal'].max():.0f} kcal"
    )
    return merged.reset_index(drop=True)


if __name__ == "__main__":
    DATA_DIR.mkdir(exist_ok=True)
    dataset = build()
    dataset.to_csv(OUTPUT, index=False)
    print(f"\nWrote {OUTPUT} ({len(dataset)} rows, {len(dataset.columns)} columns)")
